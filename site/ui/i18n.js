export const LangContext = createContext("en");

/** Translation function for the current language. */
export function useT() {
    const lang = useContext(LangContext);
    const strings = STRINGS[lang] ?? STRINGS.en;
    return Object.assign((key, ...args) => {
        const value = strings[key] ?? STRINGS.en[key] ?? key;
        return typeof value === "function" ? value(...args) : value;
    }, { lang, label: (name) => LABELS[name]?.[lang] ?? LABELS[name]?.en ?? name });
}

export function initialLang() {
    try {
        const saved = localStorage.getItem("bantulex-lang");
        if (saved && LANGUAGES.includes(saved)) return saved;
    } catch {}
    return navigator.language?.toLowerCase().startsWith("nl") ? "nl" : "en";
}
